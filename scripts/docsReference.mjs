// Builds docs/reference/commands.md and docs/reference/settings.md from package.json,
// so the reference pages list every command and setting with their real defaults.
// Run: node scripts/docsReference.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const COMMANDS_PATH = fileURLToPath(new URL('../docs/reference/commands.md', import.meta.url));
export const SETTINGS_PATH = fileURLToPath(new URL('../docs/reference/settings.md', import.meta.url));

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));

const GENERATED = '<!-- Generated by scripts/docsReference.mjs from package.json. Do not edit by hand. -->';

/** Text that is safe inside one Markdown table cell. */
function cell(text) {
  return text.replace(/\r?\n+/g, ' ').replace(/\|/g, '\\|').trim();
}

function shortcut(binding) {
  const mac = (k) =>
    k
      .split('+')
      .map((p) => ({ cmd: '⌘', alt: '⌥', ctrl: '⌃', shift: '⇧' })[p] ?? p.toUpperCase())
      .join('');
  const pc = (k) =>
    k
      .split('+')
      .map((p) => ({ alt: 'Alt', ctrl: 'Ctrl', shift: 'Shift' })[p] ?? p.toUpperCase())
      .join('+');
  return binding.mac ? `\`${mac(binding.mac)}\` / \`${pc(binding.key)}\`` : `\`${pc(binding.key)}\``;
}

export function buildCommands() {
  const hidden = new Set(
    (pkg.contributes.menus?.commandPalette ?? []).filter((m) => m.when === 'false').map((m) => m.command)
  );
  const keys = new Map((pkg.contributes.keybindings ?? []).map((b) => [b.command, shortcut(b)]));
  const seen = new Set();
  const rows = [];
  for (const c of pkg.contributes.commands) {
    const title = `${c.category ? `${c.category}: ` : ''}${c.title}`;
    if (hidden.has(c.command) || seen.has(title)) {
      continue;
    }
    seen.add(title);
    rows.push(`| ${cell(title)} | \`${c.command}\` | ${keys.get(c.command) ?? ''} |`);
  }
  return [
    '# Commands',
    '',
    GENERATED,
    '',
    'Every command below is in the **Command Palette** (`⇧⌘P` / `Ctrl+Shift+P`). Some show only when they apply, for example the Track Changes commands while changes are being tracked. Buttons in the Overtex sidebar views and the PDF preview run further commands that are not listed here.',
    '',
    'Change a shortcut in **Preferences: Open Keyboard Shortcuts** by searching for the command ID.',
    '',
    '| Command | ID | Shortcut |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

function defaultValue(v) {
  if (v.default === undefined) {
    return '';
  }
  if (v.default === '') {
    return '*(empty)*';
  }
  return `\`${JSON.stringify(v.default)}\``;
}

function type(v) {
  if (v.enum) {
    return v.enum.map((e) => `\`${e}\``).join(', ');
  }
  return Array.isArray(v.type) ? v.type.join(' or ') : (v.type ?? '');
}

export function buildSettings() {
  const props = pkg.contributes.configuration.properties;
  const groups = new Map();
  for (const [key, v] of Object.entries(props)) {
    const group = key.split('.')[1];
    if (!groups.has(group)) {
      groups.set(group, []);
    }
    const desc = cell(v.markdownDescription ?? v.description ?? '');
    groups.get(group).push(`| \`${key}\` | ${type(v)} | ${defaultValue(v)} | ${desc} |`);
  }
  const sections = [];
  for (const [group, rows] of groups) {
    sections.push(`## ${group}`, '', '| Setting | Values | Default | Description |', '| --- | --- | --- | --- |', ...rows, '');
  }
  return [
    '# Settings',
    '',
    GENERATED,
    '',
    'Open **Preferences: Open Settings (UI)** and search for `overtex`, or add these to `settings.json`. In an [untrusted workspace](../privacy.md#workspace-trust) Overtex ignores the workspace values of settings that name a program to run or an address to send text to.',
    '',
    ...sections,
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(COMMANDS_PATH, buildCommands());
  writeFileSync(SETTINGS_PATH, buildSettings());
}
